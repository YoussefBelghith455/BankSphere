export type TranslationKey = {
  [Section in keyof typeof translations.en]:
    `${Section}.${keyof typeof translations.en[Section] & string}`
}[keyof typeof translations.en];

@Injectable({
  providedIn: 'root'
})
export class Translation {
  private readonly preferences = inject(Preferences);

  readonly language = this.preferences.language;
  readonly isRtl = this.preferences.isRtl;

  readonly dictionary = computed(
    () => translations[this.language()]
  );

  translate(key: TranslationKey): string {
    const [section, item] = key.split('.') as [
      keyof typeof translations.en,
      string
    ];

    const dictionary = this.dictionary() as unknown as Record<
      string,
      Record<string, string>
    >;

    return dictionary[section]?.[item] ?? key;
  }
}
